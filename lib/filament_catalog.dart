List<CatalogFilament> catalogSuggestions(String brand, String query) {
  final normalized = query
      .trim()
      .toLowerCase()
      .replaceAll('translúcido', 'transparent')
      .replaceAll('translucido', 'transparent')
      .replaceAll('transparente', 'transparent')
      .replaceAll('rojo', 'red')
      .replaceAll('naranja', 'orange')
      .replaceAll('amarillo', 'yellow')
      .replaceAll('verde', 'green')
      .replaceAll('azul', 'blue')
      .replaceAll('morado', 'purple')
      .replaceAll('violeta', 'purple')
      .replaceAll('rosa', 'pink')
      .replaceAll('blanco', 'white')
      .replaceAll('negro', 'black')
      .replaceAll('gris', 'grey');
  if (normalized.isEmpty) return [];
  final terms = normalized.split(RegExp(r'\s+'));
  final matches = filamentCatalog.where((item) {
    if (item.brand != brand) return false;
    final searchable = '${item.name} ${item.material}'.toLowerCase();
    return terms.every(searchable.contains);
  });
  final unique = <String, CatalogFilament>{};
  for (final item in matches) {
    unique['${item.name}|${item.material}|${item.color}'] = item;
  }
  return unique.values.take(8).toList();
}
